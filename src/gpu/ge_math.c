float ge_recip(float w){
	u32 bits, i;
	int e;
	const RecipSegment *seg;
	s32 q;
	memcpy(&bits, &w, 4);
	i = (bits >> 8) & 0x7FFF;
	e = (int)((bits >> 23) & 0xFF) - 127;
	seg = &recip_segments[i >> 8];
	q = (64 * seg->b + 63 + seg->m * (s32)(i & 255)) >> 7;
	return copysignf(ldexpf((float)q, -16 - e), w);
}

float ge_rsqrt(float d){
	u32 bits, i;
	int e;
	const RecipSegment *seg;
	s32 q;
	memcpy(&bits, &d, 4);
	i = (bits >> 8) & 0x7FFF;
	e = (int)((bits >> 23) & 0xFF) - 127;
	seg = &rsqrt_segments[e & 1][i >> 8];
	q = (64 * seg->b + 63 + seg->m * (s32)(i & 255)) >> 7;
	return ldexpf((float)q, -16 - (e >> 1));
}

float ge_add(float a, float b){
	u32 ba, bb;
	int ea, eb, emax, na, nb;
	memcpy(&ba, &a, 4);
	memcpy(&bb, &b, 4);
	ea = (int)((ba >> 23) & 0xFF);
	eb = (int)((bb >> 23) & 0xFF);
	if(ea == 0 || eb == 0) return ea == 0 ? (eb == 0 ? 0.0f : ge_trunc24(b)) : ge_trunc24(a);
	emax = ea > eb ? ea : eb;
	na = 8 + emax - ea;
	nb = 8 + emax - eb;
	ba = na >= 24 ? (ba & 0x80000000u) : (ba & ~((1u << na) - 1));
	bb = nb >= 24 ? (bb & 0x80000000u) : (bb & ~((1u << nb) - 1));
	memcpy(&a, &ba, 4);
	memcpy(&b, &bb, 4);
	return a + b;
}

GeRowTerm ge_product(float a, float b){
	GeRowTerm t;
	u32 ba, bb;
	int ea, eb;
	u64 ma, mb;
	s32 m;
	memcpy(&ba, &a, 4);
	memcpy(&bb, &b, 4);
	ea = (int)((ba >> 23) & 0xFF);
	eb = (int)((bb >> 23) & 0xFF);
	if(ea == 0 || eb == 0){ t.mantissa = 0; t.lsb_exp = INT_MIN; return t; }
	ma = (ba & 0x007FFFFFu) | 0x00800000u;
	mb = (bb & 0x007FFFFFu) | 0x00800000u;
	m = (s32)((ma * mb) >> 31);
	t.mantissa = ((ba ^ bb) & 0x80000000u) ? -m : m;
	t.lsb_exp = (ea - 127) + (eb - 127) - 15;
	return t;
}

float ge_row_sum(const GeRowTerm *terms, int count){
	int lsb = INT_MIN, i;
	s32 sum = 0;
	for(i = 0; i < count; i++) if(terms[i].lsb_exp > lsb) lsb = terms[i].lsb_exp;
	for(i = 0; i < count; i++){
		s32 m = terms[i].mantissa;
		int shift = lsb - terms[i].lsb_exp;
		if(m != 0 && shift < 32) sum += m < 0 ? -((-m) >> shift) : (m >> shift);
	}
	if(sum == 0) return 0.0f;
	return ge_trunc24(ldexpf((float)sum, lsb));
}

float ge_clip_component(const float *v, const float *m, int c){
	GeRowTerm t[4];
	t[0] = ge_product(ge_trunc24(v[0]), m[c]);
	t[1] = ge_product(ge_trunc24(v[1]), m[4 + c]);
	t[2] = ge_product(ge_trunc24(v[2]), m[8 + c]);
	t[3] = ge_product(1.0f, m[12 + c]);
	return ge_row_sum(t, 4);
}

void ge_combine_matrices(float *out, const float *a, const float *b){
	int r, c, k;
	for(r = 0; r < 4; r++)
		for(c = 0; c < 4; c++){
			GeRowTerm t[4];
			for(k = 0; k < 4; k++) t[k] = ge_product(a[r * 4 + k], b[k * 4 + c]);
			out[r * 4 + c] = ge_row_sum(t, 4);
		}
}

float ge_viewport(float clip_c, float clip_w, float scale, float center){
	float w = ge_trunc24(clip_w), ndc;
	if(!isfinite(w) || !isfinite(clip_c) || fabsf(w) < 1.17549435e-38f)
		return clip_c * scale / clip_w + center;
	ndc = ge_product24((double)ge_trunc24(clip_c) * ge_recip(w));
	return ge_add(ge_product24((double)ndc * scale), center);
}
